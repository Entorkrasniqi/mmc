"""Generate the XTCE mission database for Yamcs from the specification.

XTCE (XML Telemetric and Command Exchange, an OMG/CCSDS standard) is a vendor-neutral XML format that describes
*what the bytes of every packet mean*: where each parameter sits, how to convert it, what its alarm limits are, which
commands exist and how to build them. Yamcs reads such a file (the "MDB", mission database) and from then on can decode
telemetry and encode commands without any satellite-specific code.

Writing a few hundred lines of XTCE by hand - and keeping it consistent with the simulator - is tedious and error-prone.
So this module *generates* it from the same YAML specification the simulator uses. The structure follows the
conventions of Yamcs' own quickstart example.
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from typing import Dict, Optional

from .spec import CommandSpec, Field, Limits, ScalarType, Spec

__all__ = ["generate_xtce", "NS"]

NS = "http://www.omg.org/spec/XTCE/20180204"
XSI = "http://www.w3.org/2001/XMLSchema-instance"
ET.register_namespace("", NS)
ET.register_namespace("xsi", XSI)


def _q(tag: str) -> str:
    return f"{{{NS}}}{tag}"


def _el(parent: ET.Element, tag: str, **attrib) -> ET.Element:
    return ET.SubElement(parent, _q(tag), {k: str(v) for k, v in attrib.items() if v is not None})


def _num(v: float) -> str:
    """Format a limit without a pointless trailing '.0'."""
    return str(int(v)) if float(v).is_integer() else repr(float(v))


# ------------------------------------------------------------------------------------------------ type builders

def _encoding(parent: ET.Element, t: ScalarType) -> None:
    if t.kind == "float":
        _el(parent, "FloatDataEncoding", sizeInBits=t.bits)
    elif t.kind == "int":
        _el(parent, "IntegerDataEncoding", encoding="twosComplement", sizeInBits=t.bits)
    else:
        _el(parent, "IntegerDataEncoding", sizeInBits=t.bits)       # unsigned is the default


def _units(parent: ET.Element, unit: Optional[str]) -> None:
    units = _el(parent, "UnitSet")
    if unit:
        unit_el = _el(units, "Unit")
        unit_el.text = unit


def _enum_list(parent: ET.Element, labels: Dict[str, int]) -> None:
    lst = _el(parent, "EnumerationList")
    for label, value in sorted(labels.items(), key=lambda kv: kv[1]):
        _el(lst, "Enumeration", value=value, label=label)


def _alarm(parent: ET.Element, limits: Limits) -> None:
    alarm = _el(parent, "DefaultAlarm")
    ranges = _el(alarm, "StaticAlarmRanges")
    for tag, pair in (("WarningRange", limits.warning), ("CriticalRange", limits.critical)):
        if pair:
            lo, hi = pair
            _el(ranges, tag, minInclusive=None if lo is None else _num(lo),
                maxInclusive=None if hi is None else _num(hi))


def _ccsds_header_types(types: ET.Element, kind: str) -> None:
    """The CCSDS primary-header building blocks, as parameter types (kind='Parameter') or argument types ('Argument')."""
    int_t, bool_t, enum_t = f"Integer{kind}Type", f"Boolean{kind}Type", f"Enumerated{kind}Type"

    def integer(name, bits, unit=None):
        e = _el(types, int_t, name=name, signed="false")
        _units(e, unit)
        _el(e, "IntegerDataEncoding", sizeInBits=bits)

    def boolean(name, zero, one):
        e = _el(types, bool_t, name=name, zeroStringValue=zero, oneStringValue=one)
        _units(e, None)
        _el(e, "IntegerDataEncoding", sizeInBits=1)

    integer("CCSDS_Version_Type", 3)
    boolean("CCSDS_Type_Type", "TM", "TC")
    boolean("CCSDS_Sec_Hdr_Flag_Type", "NotPresent", "Present")
    integer("CCSDS_APID_Type", 11)
    e = _el(types, enum_t, name="CCSDS_Group_Flags_Type")
    _units(e, None)
    _el(e, "IntegerDataEncoding", sizeInBits=2)
    _enum_list(e, {"Continuation": 0, "First": 1, "Last": 2, "Standalone": 3})
    integer("CCSDS_Source_Sequence_Count_Type", 14)
    integer("CCSDS_Packet_Length_Type", 16, unit="Octets")


# ------------------------------------------------------------------------------------------------ the generator

def generate_xtce(spec: Spec) -> str:
    root = ET.Element(_q("SpaceSystem"), {
        "name": spec.mission_name,
        f"{{{XSI}}}schemaLocation": f"{NS} https://www.omg.org/spec/XTCE/20180204/SpaceSystem.xsd"})
    root.append(ET.Comment(" GENERATED by 'minisat gen-xtce' from spec/minisat.yaml - do not edit by hand. "))

    _telemetry(root, spec)
    _commands(root, spec)

    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def _parameter_type_name(f: Field) -> str:
    """Name of the parameter type used by field ``f`` (types are shared where sharing is honest)."""
    if f.enum:
        return f"{f.enum}_{f.type.name}_t"
    if f.unit is None and f.limits is None:
        return f"{f.type.name}_t"
    return f"{f.name}_t"


def _telemetry(root: ET.Element, spec: Spec) -> None:
    tm = _el(root, "TelemetryMetaData")
    types = _el(tm, "ParameterTypeSet")

    # --- framing types
    agg = _el(types, "AggregateParameterType", name="CCSDS_Packet_ID_Type")
    members = _el(agg, "MemberList")
    for name, ref in (("Version", "CCSDS_Version_Type"), ("Type", "CCSDS_Type_Type"),
                      ("SecHdrFlag", "CCSDS_Sec_Hdr_Flag_Type"), ("APID", "CCSDS_APID_Type")):
        _el(members, "Member", name=name, typeRef=ref)
    agg = _el(types, "AggregateParameterType", name="CCSDS_Packet_Sequence_Type")
    members = _el(agg, "MemberList")
    _el(members, "Member", name="GroupFlags", typeRef="CCSDS_Group_Flags_Type")
    _el(members, "Member", name="Count", typeRef="CCSDS_Source_Sequence_Count_Type")
    _ccsds_header_types(types, "Parameter")
    t = _el(types, "IntegerParameterType", name="SpacecraftTime_Type", signed="false",
            shortDescription="Milliseconds since 1970-01-01T00:00:00 UTC")
    _units(t, "ms")
    _el(t, "IntegerDataEncoding", sizeInBits=64)

    # --- mission types, one per distinct (enum/type/unit/limits) use
    done = set()
    for f in spec.all_tm_fields():
        name = _parameter_type_name(f)
        if name in done:
            continue
        done.add(name)
        if f.enum:
            e = _el(types, "EnumeratedParameterType", name=name)
            _units(e, None)
            _encoding(e, f.type)
            _enum_list(e, spec.enums[f.enum])
        elif f.type.kind == "float":
            e = _el(types, "FloatParameterType", name=name)
            _units(e, f.unit)
            _encoding(e, f.type)
            if f.limits:
                _alarm(e, f.limits)
        else:
            e = _el(types, "IntegerParameterType", name=name, signed="true" if f.type.kind == "int" else "false")
            _units(e, f.unit)
            _encoding(e, f.type)
            if f.limits:
                _alarm(e, f.limits)

    # --- parameters
    params = _el(tm, "ParameterSet")
    _el(params, "Parameter", name="CCSDS_Packet_ID", parameterTypeRef="CCSDS_Packet_ID_Type")
    _el(params, "Parameter", name="CCSDS_Packet_Sequence", parameterTypeRef="CCSDS_Packet_Sequence_Type")
    _el(params, "Parameter", name="CCSDS_Packet_Length", parameterTypeRef="CCSDS_Packet_Length_Type")
    _el(params, "Parameter", name="sc_time_ms", parameterTypeRef="SpacecraftTime_Type",
        shortDescription="Spacecraft clock when the packet was generated")
    for f in spec.all_tm_fields():
        _el(params, "Parameter", name=f.name, parameterTypeRef=_parameter_type_name(f),
            shortDescription=f.description or None)

    # --- containers (packet layouts)
    containers = _el(tm, "ContainerSet")
    ccsds = _el(containers, "SequenceContainer", name="CCSDSPacket", abstract="true")
    entries = _el(ccsds, "EntryList")
    for p in ("CCSDS_Packet_ID", "CCSDS_Packet_Sequence", "CCSDS_Packet_Length"):
        _el(entries, "ParameterRefEntry", parameterRef=p)
    telemetry = _el(containers, "SequenceContainer", name="TelemetryPacket")
    _el(telemetry, "EntryList")
    base = _el(telemetry, "BaseContainer", containerRef="CCSDSPacket")
    comp = _el(_el(base, "RestrictionCriteria"), "ComparisonList")
    _el(comp, "Comparison", value="0", parameterRef="CCSDS_Packet_ID/Version")
    _el(comp, "Comparison", value="TM", parameterRef="CCSDS_Packet_ID/Type")

    for pkt in spec.tm_packets:
        c = _el(containers, "SequenceContainer", name=pkt.name, shortDescription=pkt.description or None)
        entries = _el(c, "EntryList")
        _el(entries, "ParameterRefEntry", parameterRef="sc_time_ms")
        for f in pkt.fields:
            _el(entries, "ParameterRefEntry", parameterRef=f.name)
        base = _el(c, "BaseContainer", containerRef="TelemetryPacket")
        comp = _el(_el(base, "RestrictionCriteria"), "ComparisonList")
        _el(comp, "Comparison", value="Present", parameterRef="CCSDS_Packet_ID/SecHdrFlag")
        _el(comp, "Comparison", value=pkt.apid, parameterRef="CCSDS_Packet_ID/APID")


def _arg_type_name(cmd: CommandSpec, a: Field) -> str:
    return f"{cmd.name}_{a.name}_t"


def _commands(root: ET.Element, spec: Spec) -> None:
    cm = _el(root, "CommandMetaData")
    types = _el(cm, "ArgumentTypeSet")
    _ccsds_header_types(types, "Argument")
    t = _el(types, "IntegerArgumentType", name="Command_ID_Type", signed="false")
    _units(t, None)
    _el(t, "IntegerDataEncoding", sizeInBits=16)

    for cmd in spec.commands:
        for a in cmd.args:
            name = _arg_type_name(cmd, a)
            if a.enum:
                e = _el(types, "EnumeratedArgumentType", name=name)
                _units(e, None)
                _encoding(e, a.type)
                _enum_list(e, spec.enums[a.enum])
                continue
            tag = "FloatArgumentType" if a.type.kind == "float" else "IntegerArgumentType"
            attrs = {} if a.type.kind == "float" else {"signed": "true" if a.type.kind == "int" else "false"}
            e = _el(types, tag, name=name, **attrs)
            _units(e, a.unit)
            _encoding(e, a.type)
            if a.range:
                rng = _el(_el(e, "ValidRangeSet"), "ValidRange")
                rng.set("minInclusive", _num(a.range[0]))
                rng.set("maxInclusive", _num(a.range[1]))

    commands = _el(cm, "MetaCommandSet")

    # level 1: the CCSDS primary header. Abstract: nobody sends it alone.
    base = _el(commands, "MetaCommand", name="CCSDS_TC", abstract="true")
    args = _el(base, "ArgumentList")
    for name, ref in (("CCSDS_Version", "CCSDS_Version_Type"), ("CCSDS_Type", "CCSDS_Type_Type"),
                      ("CCSDS_Sec_Hdr_Flag", "CCSDS_Sec_Hdr_Flag_Type"), ("CCSDS_APID", "CCSDS_APID_Type"),
                      ("CCSDS_Group_Flags", "CCSDS_Group_Flags_Type"), ("CCSDS_Packet_Length", "CCSDS_Packet_Length_Type")):
        _el(args, "Argument", argumentTypeRef=ref, name=name)
    cont = _el(base, "CommandContainer", name="CCSDS_TC")
    entries = _el(cont, "EntryList")
    for name in ("CCSDS_Version", "CCSDS_Type", "CCSDS_Sec_Hdr_Flag", "CCSDS_APID", "CCSDS_Group_Flags"):
        _el(entries, "ArgumentRefEntry", argumentRef=name)
    _el(entries, "FixedValueEntry", name="CCSDS_Source_Sequence_Count", binaryValue="0000", sizeInBits=14)
    _el(entries, "ArgumentRefEntry", argumentRef="CCSDS_Packet_Length")

    # level 2: this mission's header fields: fixed APID, plus the command id
    mission = _el(commands, "MetaCommand", name=f"{spec.mission_name}_TC", abstract="true")
    bmc = _el(mission, "BaseMetaCommand", metaCommandRef="CCSDS_TC")
    assign = _el(bmc, "ArgumentAssignmentList")
    for name, value in (("CCSDS_Version", 0), ("CCSDS_Type", "TC"), ("CCSDS_Sec_Hdr_Flag", "NotPresent"),
                        ("CCSDS_APID", spec.tc_apid), ("CCSDS_Group_Flags", "Standalone")):
        _el(assign, "ArgumentAssignment", argumentName=name, argumentValue=value)
    _el(_el(mission, "ArgumentList"), "Argument", argumentTypeRef="Command_ID_Type", name="Command_ID")
    cont = _el(mission, "CommandContainer", name=f"{spec.mission_name}_TC")
    _el(_el(cont, "EntryList"), "ArgumentRefEntry", argumentRef="Command_ID")
    _el(cont, "BaseContainer", containerRef="CCSDS_TC")

    # level 3: one MetaCommand per command. The CCSDS length field is a constant per command
    # (header-less size - 1), so it is simply "assigned" here instead of computed by custom code at run time.
    for cmd in spec.commands:
        mc = _el(commands, "MetaCommand", name=cmd.name, shortDescription=cmd.description or None)
        bmc = _el(mc, "BaseMetaCommand", metaCommandRef=f"{spec.mission_name}_TC")
        assign = _el(bmc, "ArgumentAssignmentList")
        _el(assign, "ArgumentAssignment", argumentName="Command_ID", argumentValue=cmd.id)
        _el(assign, "ArgumentAssignment", argumentName="CCSDS_Packet_Length", argumentValue=cmd.data_size - 1)
        if cmd.args:
            arglist = _el(mc, "ArgumentList")
            for a in cmd.args:
                _el(arglist, "Argument", argumentTypeRef=_arg_type_name(cmd, a), name=a.name,
                    shortDescription=a.description or None)
        cont = _el(mc, "CommandContainer", name=cmd.name)
        entries = _el(cont, "EntryList")
        for a in cmd.args:
            _el(entries, "ArgumentRefEntry", argumentRef=a.name)
        _el(cont, "BaseContainer", containerRef=f"{spec.mission_name}_TC")
        if cmd.significance:
            _el(mc, "DefaultSignificance", consequenceLevel=cmd.significance)
